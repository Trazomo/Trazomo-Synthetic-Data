// HR-12 compensation-band-dataset: the guard over the band library, over the
// join between the general ledger and what this company pays, and over the two
// places the file carries a finding a reader has to compute rather than read.
//
// Four disciplines run through every check.
//
//   * No test names the employee paid above their own band, the group whose two
//     cohort means sit apart, or the band either of them belongs to. Both are
//     found by rule over the emitted bytes and asserted by cardinality, so a
//     reroll that moves one stays green and a reroll that destroys one fails.
//   * The population, the ledger, the review cycle, the mixed sensitivity
//     record set and the artifacts/ name sweep are read off disk here, never
//     through the shared builder the generator uses, because the claim under
//     test is that this artifact agrees with the committed pack rather than
//     that two calls of one function agree.
//   * The column lists come out of spec.files rather than being restated, so a
//     dropped column is a red gate.
//   * The published vocabularies and the three multiplier tables are restated
//     literally below, parsed back out of the shipped grammar row and asserted
//     equal to the generator's exported copies, the HR-18 discipline, so a
//     vocabulary edit changes one side and the test says so.
//
// The header parse the frozen one-to-one pair needs is two regular expressions
// over two markdown lines, a handful of lines of local code that does not earn
// a helper. tests/helpers/csv-table.js reads the seven CSVs and
// tests/helpers/money-shape.js runs the money screen; nothing under
// tests/helpers/ is edited.
