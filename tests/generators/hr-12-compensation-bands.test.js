test("HR-C6-T8: the cohort is a function of group membership and a seed, and of nothing else in the pack", () => {
  // The structural claim, in three parts. First: the split is balanced inside
  // every group, so a group's evaluability cannot be a property of the draw.
  for (const group of groupList) {
    assert.ok(Math.abs(group.cohort_a.length - group.cohort_b.length) <= 1);
  }

  // Second: no attribute in the pack determines the cohort. For every value of
  // every attribute a reader could reach for, with at least two people in it,
  // both cohorts appear, so knowing the attribute tells a reader nothing.
  const tenures = employees.map((row) => tenureMonths(row.employee_id)).sort((a, b) => a - b);
  const decileOf = (months) => Math.min(9, Math.floor((10 * tenures.filter((t) => t < months).length) / tenures.length));
  const attributes = {
    work_location: (row) => row.work_location,
    department: (row) => rosterById.get(row.employee_id).department,
    level: (row) => rosterById.get(row.employee_id).level,
    tenure_decile: (row) => String(decileOf(tenureMonths(row.employee_id))),
    surname_initial: (row) => rosterById.get(row.employee_id).last_name[0],
  };
  for (const [name, read] of Object.entries(attributes)) {
    const classes = new Map();
    for (const row of employees) {
      const value = read(row);
      if (!classes.has(value)) classes.set(value, new Set());
      classes.get(value).add(row.synthetic_equity_cohort);
    }
    for (const [value, seen] of classes) {
      const size = employees.filter((row) => read(row) === value).length;
      if (size < 2) continue;
      assert.equal(seen.size, 2, `knowing ${name} is ${value} would tell a reader the cohort`);
    }
  }

  // Third: the split moves when the seed moves and nothing else does. A shuffle
  // of the same members under a different stream name lands on a different
  // partition in all but a handful of groups, which is what "a function of the
  // group and the seed alone" means when it is checked rather than asserted.
  const alternative = createRng("HR-12", "equity-cohort-alternative");
  let moved = 0;
  for (const group of evaluableGroups) {
    const members = [...group.cohort_a, ...group.cohort_b]
      .map((row) => row.employee_id).sort();
    const shuffled = alternative.shuffle(members);
    const drawn = new Set(shuffled.slice(0, Math.ceil(members.length / 2)));
    const shippedA = new Set(group.cohort_a.map((row) => row.employee_id));
    const same = drawn.size === shippedA.size && [...drawn].every((employeeId) => shippedA.has(employeeId));
    if (!same) moved += 1;
  }
  assert.ok(moved >= EVALUABLE_GROUPS - 4, `only ${moved} of ${EVALUABLE_GROUPS} evaluable groups split differently under a different stream`);

  // And the pay file carries nothing a cohort could have been derived from.
  for (const column of ["first_name", "last_name", "email", "gender", "ethnicity", "age", "date_of_birth"]) {
    assert.ok(!employeeTable.cols.includes(column));
  }
});

