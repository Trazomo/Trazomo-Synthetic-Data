/** The frozen one to one pair, read off its own two documents and resolved against the roster. */
function readFrozenPair() {
  const text = readFileSync(join(REPO_ROOT, "artifacts", "HR-09", "one-to-one-log.md"), "utf8");
  return ["Manager", "Report"].map((label) => {
    const match = new RegExp(`^- ${label}: (.+?) \\((.+?)\\)$`, "m").exec(text);
    assert.ok(match, `the frozen one to one log carries no "- ${label}:" line`);
    const rows = activeRoster.filter(
      (row) => `${row.first_name} ${row.last_name}` === match[1].trim() && row.role_title === match[2].trim()
    );
    assert.equal(rows.length, 1, `the frozen one to one ${label} resolves to ${rows.length} active roster rows`);
    return rows[0].employee_id;
  });
}

/** Every active employee named by full name somewhere under artifacts/. */
function namedInArtifacts() {
  const root = join(REPO_ROOT, "artifacts");
  const corpus = readdirSync(root, { recursive: true })
    .map(String)
    .filter((name) => name.endsWith(".md") || name.endsWith(".json"))
    .map((name) => readFileSync(join(root, name), "utf8"))
    .join("\n");
  const named = new Set();
  for (const row of activeRoster) {
    if (corpus.includes(`${row.first_name} ${row.last_name}`)) named.add(row.employee_id);
  }
  return named;
}
