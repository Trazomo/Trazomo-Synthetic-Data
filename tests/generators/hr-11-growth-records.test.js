test("HR-C5-T11: the key orders, the id blocks, and the absences the house rules require", () => {
  assert.deepEqual(Object.keys(grammar), PUBLISHED_KEY_ORDERS.grammar);
  assert.deepEqual(Object.keys(goalSet), PUBLISHED_KEY_ORDERS.goalSet);
  assert.deepEqual(Object.keys(selfSet), PUBLISHED_KEY_ORDERS.selfAssessmentSet);
  for (const goal of goals) assert.deepEqual(Object.keys(goal), PUBLISHED_KEY_ORDERS.goal);
  for (const record of assessments) {
    assert.deepEqual(Object.keys(record), PUBLISHED_KEY_ORDERS.selfAssessment);
    for (const entry of record.entries) assert.deepEqual(Object.keys(entry), PUBLISHED_KEY_ORDERS.entry);
  }
  assert.deepEqual(KEY_ORDERS, PUBLISHED_KEY_ORDERS, "the generator's exported key orders have moved");

  const goalIds = goals.map((goal) => goal.goal_id);
  assert.equal(new Set(goalIds).size, goalIds.length, "a goal id appears twice");
  goalIds.forEach((goalId, index) => {
    assert.equal(goalId, `GOL-2026-${String(index + 1).padStart(4, "0")}`, "the goal ids are not dense");
  });
  const sortedGoals = [...goals].sort(
    (a, b) => a.employee_id.localeCompare(b.employee_id) || a.competency_id.localeCompare(b.competency_id)
  );
  assert.deepEqual(sortedGoals.map((goal) => goal.goal_id), goalIds, "the goal ids are out of their stated order");
  const assessmentIds = assessments.map((record) => record.self_assessment_id);
  assert.equal(new Set(assessmentIds).size, assessmentIds.length, "a self-assessment id appears twice");
  assessmentIds.forEach((assessmentId, index) => {
    assert.equal(assessmentId, `GSA-2026-${String(index + 1).padStart(4, "0")}`);
  });
  assert.deepEqual(
    [...assessments].sort((a, b) => a.employee_id.localeCompare(b.employee_id)).map((r) => r.self_assessment_id),
    assessmentIds,
    "the self-assessment ids are out of employee_id order"
  );

  const knownGoalIds = new Set(goalIds);
  const knownAssessmentIds = new Set(assessmentIds);
  const forbidden = ["salary", "pay_band", "rating", "score", "date_of_birth", "home_city", "EMP-0601", "ca-", "HRC-", "RQN-"];
  // The one exemption, and it is a field name rather than a value: the grammar
  // publishes its classification argument under `not_a_rating`, which is the
  // artifact saying it carries no rating. Every other string is swept whole, so
  // a field called `performance_rating` or a value carrying a score is caught.
  const publishedKeyExemptions = new Set(["not_a_rating"]);
  for (const text of everyEmittedString) {
    if (text.includes("GOL-")) assert.ok(knownGoalIds.has(text), `"GOL-" reaches the string "${text}"`);
    if (text.includes("GSA-")) assert.ok(knownAssessmentIds.has(text), `"GSA-" reaches the string "${text}"`);
    assert.ok(!text.includes("—") && !text.includes("–"), `an emitted string carries a long dash`);
    assert.ok(!text.includes("$") && !text.includes("%"), `an emitted string carries a money or percentage mark`);
    assert.deepEqual(moneyMatches(text), [], `an emitted string carries a money-shaped figure`);
    assert.ok(!/\d{2}:\d{2}/.test(text), "an emitted string carries a time of day");
    if (publishedKeyExemptions.has(text)) continue;
    for (const token of forbidden) {
      assert.ok(!text.includes(token), `an emitted string carries the token "${token}"`);
    }
  }
});

test("HR-C5-T15: the frozen HR-09 census still reads as the module it feeds was built against", () => {
  const sentences = hr09Draft
    .split("\n")
    .filter((line) => line.trim() !== "" && !line.startsWith("#") && !line.startsWith("- "))
    .flatMap((paragraph) => paragraph.split(/(?<=\.)\s+/))
    .map((sentence) => sentence.trim())
    .filter(Boolean);
  assert.ok(sentences.length >= 14 && sentences.length <= 18, `the draft carries ${sentences.length} sentences`);

  const anyOf = (text, tokens) => tokens.some((token) => carriesToken(text, token));
  const carriesDate = (text) =>
    /\b\d{1,2} (January|February|March|April|May|June|July|August|September|October|November|December) \d{4}\b/i
      .test(text);

  const deadlineSentences = sentences.filter((s) => anyOf(s, closedLists.deadline_lexemes));
  const characterSentences = sentences.filter((s) => anyOf(s, closedLists.character_claim_phrases));
  assert.equal(deadlineSentences.length, 3, "the deadline-lexeme population has moved");
  assert.equal(characterSentences.length, 2, "the character-phrase population has moved");

  const logEntries = hr09Log.match(/^### (\d{4}-\d{2}-\d{2})$/gm) ?? [];
  assert.equal(logEntries.length, 12, "the frozen log no longer carries twelve sessions");
  const logMonths = new Set(logEntries.map((line) => line.slice(4, 11)));
  assert.deepEqual(
    [...logMonths].sort(),
    ["2025-10", "2025-11", "2025-12", "2026-01", "2026-02", "2026-03"],
    "a month of the review period carries no logged session"
  );
  assert.ok(
    !anyOf(hr09Log, closedLists.deadline_lexemes),
    "the frozen log now carries a deadline lexeme, so the unsupported frequency claim is no longer unsupported"
  );

  const unsupportedFrequency = deadlineSentences.filter((s) => anyOf(s, closedLists.frequency_adverbs));
  assert.equal(unsupportedFrequency.length, 1, "the unsupported frequency claim census has moved");
  const unsupportedCharacter = characterSentences.filter(
    (s) => !carriesDate(s) && !anyOf(s, closedLists.log_deliverables)
  );
  assert.equal(unsupportedCharacter.length, 1, "the unsupported character claim census has moved");
  assert.notEqual(
    unsupportedFrequency[0],
    unsupportedCharacter[0],
    "the two plants are different sentences of different classes"
  );
});
