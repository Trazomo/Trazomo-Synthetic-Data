// HR-11 goals-self-assessment-records: the guard over the growth record set,
// over the total join that makes it a dataset rather than a dump, and over the
// one place a self-assessment sits two levels below its own goal.
//
// Four disciplines run through every check.
//
//   * No test names the employee whose self-assessment sits two levels below
//     their goal, and no test names a goal id or a self-assessment id that
//     carries it. The conflict is found by rule over the whole set and asserted
//     by cardinality, so a reroll that moves it stays green and a reroll that
//     destroys it fails.
//   * The population, the cycle and the approvers are read off the committed
//     datasets/hr/review-cycle-roster/ CSVs here, never through the shared
//     builder the generator uses, because the claim under test is that the two
//     artifacts agree rather than that two calls of one function agree. The
//     competency names come from the committed HR-01 register the same way.
//   * The scale, the role map, the note sentences and the three key orders are
//     restated literally below and the generator's exported copies are asserted
//     equal to them, the HR-18 discipline, so a vocabulary edit changes one side
//     and the test says so.
//   * HR-C5-T15 is a regression guard over the frozen HR-09 pair rather than a
//     check on anything this cluster writes. It lives here because it reads the
//     same closed lists the X13 sweep reads, and this cluster moves no HR-09
//     byte.
//
// The markdown parse the HR-09 census needs is a paragraph split and a sentence
// split, a handful of lines of local code that does not earn a helper. Nothing
// under tests/helpers/ is edited.
