const fullName = (row) => `${row.first_name} ${row.last_name}`;

const businessDays = (startIso, endIso) => {
  const out = [];
  for (let day = startIso; day <= endIso; day = addDays(day, 1)) if (!isWeekend(day)) out.push(day);
  return out;
};

/** Every string value anywhere in a JSON-shaped value, keys included. */
const walkStrings = (value, out = []) => {
  if (typeof value === "string") out.push(value);
  else if (Array.isArray(value)) for (const item of value) walkStrings(item, out);
  else if (value && typeof value === "object") {
    for (const [key, item] of Object.entries(value)) {
      out.push(key);
      walkStrings(item, out);
    }
  }
  return out;
};
const everyEmittedString = walkStrings([grammar, goalSet, selfSet]);

/**
 * Token matching with letter boundaries, which is the only reading the frozen
 * lists support: a bare substring sweep makes "template" a deadline lexeme and
 * a surname a frequency adverb.
 */
const carriesToken = (text, token) =>
  new RegExp(`(?<![A-Za-z])${token.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}(?![A-Za-z])`, "i").test(text);

/** HR-09's four closed lists, read out of its own spec entry rather than retyped. */
const closedLists = (() => {
  const entry = specs.byId.get("HR-09").planted_features.find((f) => f.includes("frequency_adverbs is"));
  assert.ok(entry, "the HR-09 spec entry no longer publishes its four closed lists");
  const read = (pattern) => {
    const match = pattern.exec(entry);
    assert.ok(match, `the HR-09 spec entry no longer matches ${pattern}`);
    return match[1].split(", ").map((token) => token.trim());
  };
  const lists = {
    frequency_adverbs: read(/frequency_adverbs is ([^.]+)\./),
    deadline_lexemes: read(/deadline_lexemes is ([^.]+)\./),
    character_claim_phrases: read(/character_claim_phrases is ([^.]+)\./),
    log_deliverables: read(/log_deliverables is the twelve named pieces of work the log discusses: (.+)$/),
  };
  assert.equal(lists.frequency_adverbs.length, 6);
  assert.equal(lists.deadline_lexemes.length, 8);
  assert.equal(lists.character_claim_phrases.length, 5);
  assert.equal(lists.log_deliverables.length, 12);
  return lists;
})();

