test("HR-C5-T8: one two-level delta, and every other census the record set is built to", () => {
  const entryCensus = { "2": 0, "1": 0, "0": 0, "-1": 0 };
  let twoLevelEntries = 0;
  for (const deltas of deltasByEmployee.values()) {
    for (const delta of deltas) {
      assert.ok(delta in entryCensus, `an entry sits at a delta of ${delta}`);
      entryCensus[delta] += 1;
      if (delta >= 2) twoLevelEntries += 1;
    }
  }
  assert.deepEqual(entryCensus, { "2": 1, "1": 44, "0": 100, "-1": 20 });
  assert.equal(twoLevelEntries, 1, "the two-level delta is not a single entry");

  const census = (predicate) => [...deltasByEmployee.values()].filter(predicate).length;
  assert.equal(census((deltas) => deltas.some((delta) => delta >= 2)), 1);
  assert.equal(census((deltas) => deltas.some((delta) => Math.abs(delta) >= 2)), 1, "the absolute census differs");
  assert.equal(census((deltas) => deltas.reduce((sum, delta) => sum + delta, 0) >= 2), 11);
  assert.equal(census((deltas) => deltas.some((delta) => delta > 0)), 31);
  assert.equal(census((deltas) => deltas.some((delta) => delta < 0)), 20);
  assert.equal(census((deltas) => deltas.every((delta) => delta === 0)), 8);

  const carriers = [...deltasByEmployee.entries()].filter(([, deltas]) => deltas.some((delta) => delta >= 2));
  assert.equal(carriers.length, 1);
  for (const [employeeId, deltas] of deltasByEmployee) {
    if (employeeId === carriers[0][0]) continue;
    for (const delta of deltas) {
      assert.ok(Math.abs(delta) <= 1, `a second employee sits ${delta} levels from one of their own goals`);
    }
  }
  assert.ok(
    !carriers[0][1].every((delta) => delta === 0),
    "the conflict carrier cannot also be one of the employees in agreement on all three"
  );
});

test("HR-C5-T9: the conflict carrier satisfies all six clauses, each recomputed from the committed cycle", () => {
  const [carrierId] = [...deltasByEmployee.entries()].find(([, deltas]) => deltas.some((delta) => delta >= 2));

  // clause 3 and clause 4: the single assignment outstanding and past its due date
  const pastDue = assignmentRows.filter((row) => row.submitted_date === "" && row.due_date < AS_OF);
  assert.equal(pastDue.length, 1, "the cycle no longer holds exactly one outstanding past-due assignment");

  // clause 5: the frozen pair, read off the two documents' own header lines
  const headerName = (text, label) => {
    const match = new RegExp(`^- ${label}: (.+?) \\((.+?)\\)$`, "m").exec(text);
    assert.ok(match, `the frozen HR-09 document carries no "- ${label}:" line`);
    return match[1];
  };
  const pairIds = [headerName(hr09Draft, "Manager"), headerName(hr09Draft, "Report")].map((name) => {
    const rows = roster.filter((row) => fullName(row) === name && row.employment_status === "active");
    assert.equal(rows.length, 1, `the frozen HR-09 name "${name}" does not resolve to one active row`);
    return rows[0].employee_id;
  });

  const satisfies = (employeeId) => {
    const row = rosterById.get(employeeId);
    const assignment = assignmentByReviewee.get(employeeId);
    return (
      Boolean(assignment)
      && row.level === "IC"
      && employeeId !== pastDue[0].reviewer_employee_id
      && employeeId !== pastDue[0].reviewee_employee_id
      && !pairIds.includes(employeeId)
      && rosterById.get(assignment.reviewer_employee_id).employment_status === "active"
    );
  };
  const candidates = revieweeIds.filter(satisfies);
  assert.ok(candidates.length > 0, "no reviewee satisfies the six clauses, so the conflict cannot be drawn by rule");
  assert.ok(satisfies(carrierId), "the conflict carrier fails one of the six clauses");
});

