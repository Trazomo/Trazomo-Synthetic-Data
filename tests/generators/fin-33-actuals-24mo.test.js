test("FIN-33 T-T2 and T-T7: January plus February is the beginning balance, and all three months are the ending balance", { todo: WAVE }, () => {
  const tb = new Map(buildTrialBalance().rows.map((r) => [r.account_code, r]));
  const rows = trend();
  const byAccount = new Map();
  for (const row of rows) {
    const seen = byAccount.get(row.account_code) ?? new Map();
    seen.set(row.period, toCents(row.actual_amount));
    byAccount.set(row.account_code, seen);
  }
  for (const [accountCode, months] of byAccount) {
    const balance = tb.get(accountCode);
    const opening = months.get("2026-01") + months.get("2026-02");
    assert.equal(cents(opening), balance.beginning_balance, `${accountCode}: January plus February is not the beginning balance`);
    const full = opening + months.get("2026-03");
    assert.equal(cents(full), balance.ending_balance, `${accountCode}: the quarter does not close at the ending balance`);
  }
  // TODO(wave): FIN-05 states an ending balance in the account's own direction,
  // so a credit-normal line's comparison flips. Assert both directions rather
  // than taking the absolute value, which would hide a sign error.
});

