test("FIN-33: the shape the two reconciliation rules have to hit is already fixed by frozen bytes", () => {
  const lines = templateLines();
  assert.equal(lines.length, 27, "the FIN-37 spine is no longer 27 lines, so 648 is the wrong row count");
  assert.equal(PERIODS.length, 24);
  assert.equal(PERIODS[0], "2024-04");
  assert.equal(PERIODS[23], "2026-03");
  assert.equal(lines.length * PERIODS.length, 648, "27 lines by 24 months is the whole file");

  // Rule 2 rests on the fiscal year being the calendar year, so a profit-and-loss
  // beginning balance at 2026-03-01 is exactly January plus February.
  const tb = new Map(buildTrialBalance().rows.map((r) => [r.account_code, r]));
  for (const line of lines) {
    const row = tb.get(line.account_code);
    assert.ok(row, `${line.line_id} names account ${line.account_code}, which FIN-05 does not carry`);
    assert.doesNotThrow(() => toCents(row.beginning_balance), `${line.account_code} has no parseable beginning balance`);
  }
});

