// OPS-13 cross-functional-handoff-log: the handoff log of the contract
// operations platform rollout, the co-002 side of the Copperline Software
// implementation, covering 2026-03-19 to 2026-03-31. Twenty two handoffs
// between four co-002 teams and the provider, each one either closed by an
// acknowledgement, still open on the receiving side, or not yet sent.
//
// A handoff is only closed when the receiving team says so, which is why the
// two timestamps are separate columns rather than one status word: the row that
// matters to module 24 is the one where the sending team finished and nobody on
// the other side ever picked it up.
//
// Team values are roster department bytes or the provider's own name, so a
// reader can resolve a party against CORE-04 without a mapping table. The one
// provider person is the engagement director CORE-01 Exhibit B.2 names, and she
// carries no employee id because she is not on the roster.
//
// Planted features (spec OPS-13), each a census over the emitted bytes:
//   P1. exactly one row populates sender_completed_at and leaves
//       receiver_acknowledged_at empty. It runs from Engineering to the
//       provider and was completed 2026-03-23, so the open acknowledgement is
//       cross-company and several business days old when the period closes.
//   P2. exactly one notes cell instructs the tracker to record the
//       acknowledgement on the receiver's behalf. It sits on an in-flight row
//       with both timestamps empty, so it is a different row from P1 and cannot
//       be reached by looking for the dangling acknowledgement.
//
// Every census is asserted before the builder returns (the FIN-38 "the builder
// refuses to emit" precedent) and re-derived from the generated bytes in
// tests/generators/ops-13-handoff-log.test.js.
