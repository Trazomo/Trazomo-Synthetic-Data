// FIN-35 inbound-requests-queue: the untriaged finance inbox at 2026-04-06,
// the fixture module 11 routes. Thirty-eight requests, none of them classified:
// `status` is pending_classification on every row, which is what makes routing a
// live decision rather than a post mortem (the FIN-08 unreleased-run precedent).
//
// Nothing in the queue is invented. Every vendor invoice points at a FIN-07
// invoice_number and carries that invoice's own amount, purchase order and due
// date; every expense report points at a FIN-13 report_id and carries its
// report_total; every submitter is an active CORE-04 employee; and the one row
// finance cannot route on its own carries the invoice number, the amount and the
// matter reference the shipped CORE-02 invoice.json already holds, read out of
// the CORE-02 generator rather than retyped. A FIN-07 or FIN-13 reroll therefore
// changes this file rather than leaving a queue row pointing at nothing.
//
// The vendor requests amend existing vendor master records rather than opening
// new ones: every counterparty in this pack is already a screened name, and
// inventing an unscreened company to "set up" is exactly what the canon ground
// rules forbid. FIN-39 DA-14 ("Create or amend a vendor master record") covers
// the amendment, and DA-04 is the routing decision the module prints.
//
// Planted features (spec FIN-35), each derivable by a rule over the data and
// never by a label:
//   P1. exactly one row leaves empty a cell that every other row of the same
//       request_type populates. No config states the requirement: the file is
//       its own schema, and the rule is a per-request_type column census.
//   P2. exactly one pair shares (counterparty_canon_id, reference_document,
//       amount) under two different request_ids, arriving on two different
//       channels one to three days apart. The same invoice, sent twice.
//   P3. exactly one row names a counterparty that is neither an AP vendor nor an
//       employee: the outside-counsel firm. It is the one request finance cannot
//       route on its own, and it is the only cross-track row in the file.
//
// All three are asserted before the builder returns (the FIN-38 "the builder
// refuses to emit" precedent) and re-derived from the generated bytes in
// tests/generators/fin-35-inbound-requests.test.js.
import { toCsv } from "../csv.js";
import { addDays, diffDays, rollForwardPastWeekend } from "../dates.js";
import { createRng } from "../seed.js";
import { buildProcureToPay, CANON_VENDORS_EXTENDED } from "./fin-06-procure-to-pay.js";
import { buildExpenseReports } from "./fin-13-expense-reports.js";
import { CANON_VENDORS, SOD_CONFLICT_ROLE } from "./fin-01-cash-recon.js";
import { generate as generateOutsideCounselInvoice } from "./core-02-invoice.js";
import { financeRoster } from "./finance-roles.js";

export const id = "FIN-35";

// ---------------------------------------------------------------- constants

export const COLUMNS = [
  "request_id", "received_date", "channel", "request_type", "submitter_employee_id",
  "submitter_department", "counterparty_canon_id", "counterparty_name", "subject",
  "reference_document", "po_number", "amount", "currency", "due_date", "attachment_count", "status",
];

export const QUEUE_PERIOD = { start: "2026-03-23", end: "2026-04-06" };
export const CHANNELS = ["ap_inbox", "expense_tool", "vendor_portal", "email"];
export const REQUEST_TYPES = ["vendor_invoice", "expense_report", "vendor_request", "other"];
/** Nothing in this file has been triaged yet. */
export const QUEUE_STATUS = "pending_classification";

export const TARGET_ROWS = 38;
export const VENDOR_INVOICE_COUNT = 16;
export const EXPENSE_REPORT_COUNT = 12;
export const VENDOR_REQUEST_COUNT = 8;

/** The FIN-39 row the routing module prints alongside its classification. */
export const ROUTING_DECISION_ID = "DA-04";
/** The FIN-39 row a vendor master amendment is decided under. */
export const VENDOR_MASTER_DECISION_ID = "DA-14";

/**
 * The canon vendors the FIN-35 spec names. Read from the two shipped vendor
 * lists rather than restated, so a vendor leaving the pack breaks generation
 * instead of leaving an unresolvable counterparty in the queue.
 */
export const VENDOR_POOL = [...CANON_VENDORS_EXTENDED, ...CANON_VENDORS];

/** What an AP team is asked to change on a vendor master record. */
const VENDOR_REQUEST_KINDS = [
  "Bank detail change request",
  "Remit to address change request",
  "Payment terms change request",
  "Vendor contact update request",
  "Tax form refresh request",
];

const REQUEST_ID_START = 101;

// ------------------------------------------------------------------ helpers

function cents(n) { return (n / 100).toFixed(2); }
function toCents(money) { return Math.round(Number(money) * 100); }

/** A business day inside the intake window, never past its end. */
function queueDay(isoDate) {
  const floor = isoDate < QUEUE_PERIOD.start ? QUEUE_PERIOD.start : isoDate;
  let date = rollForwardPastWeekend(floor);
  while (date > QUEUE_PERIOD.end) date = addDays(date, -1);
  return date;
}

/** Active CORE-04 AP clerks, never the roster's segregation-of-duties row. */
function apClerks(roster) {
  const clerks = roster
    .filter((r) => (
      r.role_title === "AP Clerk" && r.employment_status === "active" && r.department === "Finance" &&
      r.finance_system_role !== SOD_CONFLICT_ROLE
    ))
    .sort((a, b) => (a.employee_id < b.employee_id ? -1 : 1));
  if (clerks.length < 2) throw new Error(`${id}: fewer than two AP clerks can work the inbox`);
  return clerks;
}

// ------------------------------------------------------------------ sources

/**
 * The sixteen AP invoices the queue names: the most recently received invoices
 * from the canon vendors, whose invoice_number FIN-07 carries exactly once. An
 * invoice number FIN-07 repeats cannot resolve to one row, so it is excluded by
 * rule rather than by being noticed later.
 */
function pickVendorInvoices() {
  const { invoices } = buildProcureToPay();
  const counts = new Map();
  for (const row of invoices) counts.set(row.invoice_number, (counts.get(row.invoice_number) ?? 0) + 1);
  const vendorIds = new Set(VENDOR_POOL.map((v) => v.canon_id));
  const eligible = invoices
    .filter((row) => counts.get(row.invoice_number) === 1 && vendorIds.has(row.vendor_canon_id))
    .sort((a, b) => (
      a.received_date > b.received_date ? -1 : a.received_date < b.received_date ? 1
        : a.invoice_number < b.invoice_number ? -1 : 1
    ));
  if (eligible.length < VENDOR_INVOICE_COUNT) {
    throw new Error(`${id}: only ${eligible.length} canon-vendor invoices resolve uniquely in FIN-07`);
  }
  return eligible.slice(0, VENDOR_INVOICE_COUNT);
}

/** The twelve most recently submitted FIN-13 reports, one row per report. */
function pickExpenseReports() {
  const reports = new Map();
  for (const row of buildExpenseReports()) {
    if (!reports.has(row.report_id)) reports.set(row.report_id, row);
  }
  const ranked = [...reports.values()].sort((a, b) => (
    a.report_submitted_date > b.report_submitted_date ? -1 : a.report_submitted_date < b.report_submitted_date ? 1
      : a.report_id < b.report_id ? -1 : 1
  ));
  if (ranked.length < EXPENSE_REPORT_COUNT) {
    throw new Error(`${id}: FIN-13 carries only ${ranked.length} reports, and the queue names ${EXPENSE_REPORT_COUNT}`);
  }
  return ranked.slice(0, EXPENSE_REPORT_COUNT);
}

/** The shipped CORE-02 invoice, generated rather than retyped. */
function readOutsideCounselInvoice() {
  const files = generateOutsideCounselInvoice({ rng: (stream) => createRng("CORE-02", stream) });
  const file = files.find((f) => f.path === "invoice.json");
  if (!file) throw new Error(`${id}: the CORE-02 generator no longer emits invoice.json`);
  return JSON.parse(file.content);
}

// ------------------------------------------------------------------ builder

/**
 * Build the intake queue. Pure: no I/O beyond the canon lookup the engine hands
 * in, no Date.now(), every draw from createRng("FIN-35", stream).
 * @param {Map} canon canon companies lookup, for the outside-counsel firm's name
 * @returns {object[]}
 */
export function buildInboundQueue(canon) {
  const roster = financeRoster();
  const clerks = apClerks(roster);
  const dateRng = createRng(id, "received-dates");
  const detailRng = createRng(id, "details");
  const plantRng = createRng(id, "planted");

  const vendorInvoices = pickVendorInvoices();
  const expenseReports = pickExpenseReports();
  const outsideCounsel = readOutsideCounselInvoice();

  const span = diffDays(QUEUE_PERIOD.start, QUEUE_PERIOD.end);
  const spread = (index, count, floor) => queueDay(
    addDays(QUEUE_PERIOD.start, Math.round((index * span) / Math.max(1, count - 1))) < floor
      ? floor
      : addDays(QUEUE_PERIOD.start, Math.round((index * span) / Math.max(1, count - 1)))
  );

  const items = [];

  // ---- vendor invoices ---------------------------------------------------
  vendorInvoices.forEach((invoice, index) => {
    items.push({
      received_date: spread(index, VENDOR_INVOICE_COUNT, invoice.received_date),
      channel: "ap_inbox",
      request_type: "vendor_invoice",
      submitter: clerks[index % clerks.length],
      counterparty_canon_id: invoice.vendor_canon_id,
      counterparty_name: invoice.vendor_name,
      subject: `Invoice for ${invoice.description}`,
      reference_document: invoice.invoice_number,
      po_number: invoice.po_number,
      amountCents: toCents(invoice.invoice_amount),
      due_date: invoice.due_date,
      attachment_count: detailRng.int(1, 3),
      source: invoice,
    });
  });

  // ---- expense reports ---------------------------------------------------
  expenseReports.forEach((report, index) => {
    const person = roster.find((r) => r.employee_id === report.employee_id);
    if (!person) throw new Error(`${id}: ${report.report_id} was submitted by someone off the roster`);
    items.push({
      received_date: spread(index, EXPENSE_REPORT_COUNT, report.report_submitted_date),
      channel: "expense_tool",
      request_type: "expense_report",
      submitter: person,
      counterparty_canon_id: "",
      counterparty_name: `${person.first_name} ${person.last_name}`,
      subject: `Expense report for ${report.employee_department}`,
      reference_document: report.report_id,
      po_number: "",
      amountCents: toCents(report.report_total),
      due_date: "",
      attachment_count: detailRng.int(1, 4),
    });
  });

  // ---- vendor master amendments ------------------------------------------
  for (let index = 0; index < VENDOR_REQUEST_COUNT; index += 1) {
    const vendor = VENDOR_POOL[index % VENDOR_POOL.length];
    items.push({
      received_date: spread(index, VENDOR_REQUEST_COUNT, QUEUE_PERIOD.start),
      channel: "vendor_portal",
      request_type: "vendor_request",
      submitter: clerks[index % clerks.length],
      counterparty_canon_id: vendor.canon_id,
      counterparty_name: vendor.name,
      subject: `${detailRng.pick(VENDOR_REQUEST_KINDS)} for ${vendor.name}`,
      reference_document: "",
      po_number: "",
      amountCents: null,
      due_date: "",
      attachment_count: detailRng.int(1, 2),
    });
  }

  // ---- P3: the cross-track routing boundary ------------------------------
  const firm = canon?.get(outsideCounsel.law_firm_id);
  if (!firm) throw new Error(`${id}: ${outsideCounsel.law_firm_id} is not in canon/companies.md`);
  items.push({
    received_date: queueDay(outsideCounsel.invoice_date),
    channel: "email",
    request_type: "other",
    submitter: clerks[0],
    counterparty_canon_id: outsideCounsel.law_firm_id,
    counterparty_name: firm.name,
    subject: `Outside counsel invoice ${outsideCounsel.invoice_number} for matter ${outsideCounsel.matter_id}`,
    reference_document: outsideCounsel.invoice_number,
    po_number: "",
    amountCents: Math.round(outsideCounsel.invoice_total * 100),
    due_date: addDays(outsideCounsel.invoice_date, 30),
    attachment_count: 1,
  });

  // ---- P2: the same invoice, sent twice ----------------------------------
  // Drawn from the invoices that reached the queue early enough for a resend to
  // still land inside the intake window, so the one-to-three-day gap is real
  // rather than clamped away at the window's edge.
  const resendPool = items.filter(
    (row) => row.request_type === "vendor_invoice" && diffDays(row.received_date, QUEUE_PERIOD.end) >= 5
  );
  if (resendPool.length === 0) throw new Error(`${id}: no invoice arrived early enough to be resent inside the window`);
  const original = plantRng.pick(resendPool);
  const resend = {
    ...original,
    received_date: queueDay(addDays(original.received_date, plantRng.int(1, 3))),
    channel: "email",
    attachment_count: original.attachment_count,
    duplicateOf: original,
  };
  const apart = diffDays(original.received_date, resend.received_date);
  if (apart < 1 || apart > 3) throw new Error(`${id}: the resend landed ${apart} days after the original`);
  items.push(resend);

  // ---- P1: the field that never arrived ----------------------------------
  // A vendor invoice with no payment terms stated. Drawn from the invoices that
  // are not part of the resend pair, so the two plants stay separable.
  const gapPool = items.filter(
    (row) => row.request_type === "vendor_invoice" && row !== original && row !== resend
  );
  if (gapPool.length === 0) throw new Error(`${id}: no invoice is free to carry the missing field`);
  plantRng.pick(gapPool).due_date = "";

  // ---- rows ---------------------------------------------------------------
  const rows = items
    .map((item, index) => ({ item, index }))
    .sort((a, b) => (
      a.item.received_date < b.item.received_date ? -1 : a.item.received_date > b.item.received_date ? 1
        : a.index - b.index
    ))
    .map(({ item }, position) => ({
      request_id: `REQ-2026-0${REQUEST_ID_START + position}`,
      received_date: item.received_date,
      channel: item.channel,
      request_type: item.request_type,
      submitter_employee_id: item.submitter.employee_id,
      submitter_department: item.submitter.department,
      counterparty_canon_id: item.counterparty_canon_id,
      counterparty_name: item.counterparty_name,
      subject: item.subject,
      reference_document: item.reference_document,
      po_number: item.po_number,
      amount: item.amountCents === null ? "" : cents(item.amountCents),
      currency: item.amountCents === null ? "" : "USD",
      due_date: item.due_date,
      attachment_count: String(item.attachment_count),
      status: QUEUE_STATUS,
    }));

  assertPlants(rows, { vendorInvoices, expenseReports, outsideCounsel });
  return rows;
}

// ----------------------------------------------------------------- assertions

function assertPlants(rows, { vendorInvoices, expenseReports, outsideCounsel }) {
  if (rows.length !== TARGET_ROWS) throw new Error(`${id}: the queue is ${rows.length} deep, expected ${TARGET_ROWS}`);

  const invoiceByNumber = new Map(vendorInvoices.map((row) => [row.invoice_number, row]));
  const reportById = new Map(expenseReports.map((row) => [row.report_id, row]));
  for (const row of rows) {
    if (row.status !== QUEUE_STATUS) throw new Error(`${id}: ${row.request_id} has already been classified`);
    if (!REQUEST_TYPES.includes(row.request_type)) throw new Error(`${id}: ${row.request_id} is a "${row.request_type}"`);
    if (!CHANNELS.includes(row.channel)) throw new Error(`${id}: ${row.request_id} arrived on "${row.channel}"`);
    if (row.received_date < QUEUE_PERIOD.start || row.received_date > QUEUE_PERIOD.end) {
      throw new Error(`${id}: ${row.request_id} was received outside the intake window`);
    }
    if ((row.currency === "USD") !== (row.amount !== "")) {
      throw new Error(`${id}: ${row.request_id} disagrees with itself about whether an amount is on the table`);
    }
    if (row.request_type === "vendor_invoice") {
      const invoice = invoiceByNumber.get(row.reference_document);
      if (!invoice) throw new Error(`${id}: ${row.request_id} cites an invoice the queue never selected`);
      if (toCents(row.amount) !== toCents(invoice.invoice_amount)) {
        throw new Error(`${id}: ${row.request_id} disagrees with FIN-07 about the amount`);
      }
      if (row.received_date < invoice.received_date) {
        throw new Error(`${id}: ${row.request_id} reached the queue before AP received the invoice`);
      }
    }
    if (row.request_type === "expense_report") {
      const report = reportById.get(row.reference_document);
      if (!report) throw new Error(`${id}: ${row.request_id} cites a report the queue never selected`);
      if (toCents(row.amount) !== toCents(report.report_total)) {
        throw new Error(`${id}: ${row.request_id} disagrees with FIN-13 about the report total`);
      }
      if (row.received_date < report.report_submitted_date) {
        throw new Error(`${id}: ${row.request_id} reached the queue before the report was submitted`);
      }
    }
  }

  // P1
  const gaps = [];
  for (const type of REQUEST_TYPES) {
    const group = rows.filter((r) => r.request_type === type);
    if (group.length < 2) continue;
    for (const column of COLUMNS) {
      const empty = group.filter((r) => r[column] === "");
      if (empty.length === 1) gaps.push(`${type}.${column}`);
    }
  }
  if (gaps.length !== 1) throw new Error(`${id}: ${gaps.length} rows miss a field their own type carries (${gaps.join(", ")}), expected 1`);

  // P2
  const groups = new Map();
  for (const row of rows) {
    if (row.reference_document === "") continue;
    const key = [row.counterparty_canon_id, row.reference_document, row.amount].join("|");
    groups.set(key, [...(groups.get(key) ?? []), row]);
  }
  const duplicates = [...groups.values()].filter((group) => group.length > 1);
  if (duplicates.length !== 1 || duplicates[0].length !== 2) {
    throw new Error(`${id}: ${duplicates.length} submissions arrived more than once, expected exactly one pair`);
  }
  if (duplicates[0][0].channel === duplicates[0][1].channel) {
    throw new Error(`${id}: the duplicate arrived on the same channel both times`);
  }

  // P3
  const vendorIds = new Set(VENDOR_POOL.map((v) => v.canon_id));
  const outside = rows.filter((r) => r.counterparty_canon_id !== "" && !vendorIds.has(r.counterparty_canon_id));
  if (outside.length !== 1) throw new Error(`${id}: ${outside.length} rows name a counterparty finance cannot route, expected 1`);
  if (outside[0].counterparty_canon_id !== outsideCounsel.law_firm_id) {
    throw new Error(`${id}: the unroutable row does not come from the outside-counsel firm`);
  }
  if (!outside[0].subject.includes(outsideCounsel.matter_id)) {
    throw new Error(`${id}: the unroutable row does not cite matter ${outsideCounsel.matter_id}`);
  }
  if (toCents(outside[0].amount) !== Math.round(outsideCounsel.invoice_total * 100)) {
    throw new Error(`${id}: the unroutable row disagrees with the CORE-02 invoice about the amount`);
  }
}

// ---------------------------------------------------------------- generate

export function generate({ canon }) {
  return [{ path: "inbound-requests-queue.csv", content: toCsv(COLUMNS, buildInboundQueue(canon)) }];
}
