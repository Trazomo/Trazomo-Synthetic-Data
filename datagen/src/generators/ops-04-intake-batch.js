/**
 * The subject as the duplicate rule sees it: lowercased, any run of leading
 * reply or forward markers removed, punctuation stripped, whitespace collapsed.
 */
export function normalizeSubject(subject) {
  let text = String(subject).toLowerCase().trim();
  for (;;) {
    const stripped = text.replace(/^(re|fwd|fw)\s*:\s*/, "");
    if (stripped === text) break;
    text = stripped;
  }
  return text.replace(/[^a-z0-9\s]/g, " ").replace(/\s+/g, " ").trim();
}

/**
 * The shipped rubric, applied to one row's own fields. The rules and their order
 * are the bytes intake-rubric.yaml publishes; this is where they are computed,
 * and the test reimplements them from the emitted YAML rather than calling here.
 */
export function rubricPriority(row) {
  const withinWindow = (days) => (
    row.requested_due_date !== ""
    && row.requested_due_date <= addBusinessDays(row.received_date, days)
  );
  if (row.blocks_work === "yes" || withinWindow(URGENT_WINDOW_DAYS)) return "urgent";
  if (row.impact_scope === "department" || row.impact_scope === "company" || withinWindow(HIGH_WINDOW_DAYS)) {
    return "high";
  }
  return "normal";
}

// ------------------------------------------------------------------ sources

/** CORE-03's own emitted bundle, parsed. Never a second copy of its facts. */
function readCore03Bundle() {
  const files = generateCore03({ rng: (stream) => createRng("CORE-03", stream) });
  const bundle = files.find((f) => f.path === "crm-seed.json");
  if (!bundle) throw new Error(`${id}: CORE-03 no longer emits crm-seed.json`);
  return JSON.parse(bundle.content);
}

/**
 * The named internal requesters: active CORE-04 rows, the executive layer left
 * out because an intake queue is filled by the people doing the work.
 */
function pickInternalRequesters(rng) {
  const roster = buildRoster(createRng("CORE-04", "roster"));
  const eligible = roster
    .filter((r) => r.employment_status === "active" && r.level !== "Executive")
    .sort((a, b) => (a.employee_id < b.employee_id ? -1 : 1));
  if (eligible.length < INTERNAL_REQUESTER_SLOTS) {
    throw new Error(`${id}: only ${eligible.length} active roster rows can raise a request`);
  }
  return { roster, requesters: rng.shuffle(eligible).slice(0, INTERNAL_REQUESTER_SLOTS) };
}

/**
 * The customer requesters: one CORE-03 contact per account, so no account
 * speaks twice, each carrying its own account's name byte for byte.
 */
function pickCustomerRequesters(rng, seed) {
  const accountsById = new Map(seed.accounts.map((a) => [a.account_id, a]));
  const picked = [];
  const seenAccounts = new Set();
  for (const contact of rng.shuffle(seed.contacts)) {
    if (seenAccounts.has(contact.account_id)) continue;
    const account = accountsById.get(contact.account_id);
    if (!account) continue;
    seenAccounts.add(contact.account_id);
    picked.push({
      name: `${contact.first_name} ${contact.last_name}`,
      org: account.name,
      contact_id: contact.contact_id,
      account_id: account.account_id,
    });
    if (picked.length === CUSTOMER_REQUESTER_SLOTS) break;
  }
  if (picked.length !== CUSTOMER_REQUESTER_SLOTS) {
    throw new Error(`${id}: CORE-03 offers only ${picked.length} accounts with a contact, and the queue names ${CUSTOMER_REQUESTER_SLOTS}`);
  }
  return picked;
}

// ------------------------------------------------------------------ builder

/**
 * Build the intake batch. Pure: no I/O, no Date.now(), every draw from a named
 * rng stream.
 * @param {(stream: string) => import("../seed.js").Rng} rng
 * @returns {{rows: object[], messages: {path: string, content: string}[], roster: object[], customers: object[]}}
 */
export function buildIntakeBatch(rng) {
  const { roster, requesters } = pickInternalRequesters(rng("internal-requesters"));
  const customers = pickCustomerRequesters(rng("customer-requesters"), readCore03Bundle());

  for (let i = 1; i < REQUESTS.length; i += 1) {
    if (REQUESTS[i].received_date < REQUESTS[i - 1].received_date) {
      throw new Error(`${id}: the request table is not in received order at index ${i}`);
    }
  }

  const messages = [];
  const rows = REQUESTS.map((request, index) => {
    const request_id = `REQ-2026-${REQUEST_ID_START + index}`;
    const who = resolveRequester(request, { requesters, customers });
    const base = {
      request_id,
      received_date: request.received_date,
      channel: request.channel,
      request_type: request.request_type,
      requester_type: who.requester_type,
      requester_employee_id: who.requester_employee_id,
      requester_name: who.requester_name,
      requester_org: who.requester_org,
      subject: request.subject,
      description: request.description,
      requested_priority: "",
      impact_scope: request.impact_scope,
      requested_due_date: request.requested_due_date,
      blocks_work: request.blocks_work,
      message_file: request.channel === "email" ? `messages/${request_id}.eml` : "",
      status: QUEUE_STATUS,
    };
    // Priority is computed from the shipped rubric, then overridden on exactly
    // the two rows the spec says carry an override: the empty cell and the
    // stated urgency the rubric disagrees with. Deriving the other sixteen is
    // what makes "every other priority-bearing row agrees" true by construction
    // rather than by inspection.
    base.requested_priority = request.priorityOverride === undefined
      ? rubricPriority(base)
      : request.priorityOverride;

    if (request.channel === "email") {
      if (who.requester_type !== "internal" || who.email === "") {
        throw new Error(`${id}: ${request_id} arrived by email without a roster address to have sent it from`);
      }
      messages.push({
        path: `messages/${request_id}.eml`,
        content: emlFor({ from: who.email, date: request.received_date, subject: request.subject, body: request.body }),
      });
    } else if (request.body !== undefined) {
      throw new Error(`${id}: ${request_id} carries a message body but did not arrive by email`);
    }
    return base;
  });

  assertPlants({ rows, messages, roster, customers });
  return { rows, messages, roster, customers };
}

function resolveRequester(request, { requesters, customers }) {
  const { requester } = request;
  if (requester.type === "vendor") {
    return {
      requester_type: "vendor",
      requester_employee_id: "",
      requester_name: VENDOR_REQUESTER_NAME,
      requester_org: VENDOR_REQUESTER_ORG,
      email: "",
    };
  }
  if (requester.type === "customer") {
    const person = customers[requester.slot];
    if (!person) throw new Error(`${id}: no customer requester in slot ${requester.slot}`);
    return {
      requester_type: "customer",
      requester_employee_id: "",
      requester_name: person.name,
      requester_org: person.org,
      email: "",
    };
  }
  if (requester.anonymous) {
    return {
      requester_type: "internal",
      requester_employee_id: "",
      requester_name: "",
      requester_org: requester.org,
      email: "",
    };
  }
  const person = requesters[requester.slot];
  if (!person) throw new Error(`${id}: no internal requester in slot ${requester.slot}`);
  return {
    requester_type: "internal",
    requester_employee_id: person.employee_id,
    requester_name: `${person.first_name} ${person.last_name}`,
    requester_org: person.department,
    email: person.email,
  };
}

function emlFor({ from, date, subject, body }) {
  if (body === undefined || body.trim() === "") {
    throw new Error(`${id}: an email-channel row reached the message writer with no body`);
  }
  return [
    `From: ${from}`,
    `To: ${INTAKE_MAILBOX}`,
    `Date: ${date}`,
    `Subject: ${subject}`,
    "",
    body,
    "",
  ].join("\n");
}

