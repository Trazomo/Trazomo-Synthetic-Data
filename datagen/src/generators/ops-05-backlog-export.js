/**
 * The people staffing the program: three active CORE-04 rows from each of
 * Operations, Engineering and Product, each department drawn on its own stream
 * so the three groups do not share a correlated sequence.
 */
export function pickOwners(rng) {
  const roster = buildRoster(createRng("CORE-04", "roster"));
  const owners = [];
  for (const department of OWNER_DEPARTMENTS) {
    const eligible = roster
      .filter((r) => r.department === department && r.employment_status === "active" && r.level !== "Executive")
      .sort((a, b) => (a.employee_id < b.employee_id ? -1 : 1));
    if (eligible.length < OWNERS_PER_DEPARTMENT) {
      throw new Error(`${id}: ${department} has only ${eligible.length} active people, and the program needs ${OWNERS_PER_DEPARTMENT}`);
    }
    owners.push(...rng(`owners-${department.toLowerCase()}`).shuffle(eligible).slice(0, OWNERS_PER_DEPARTMENT));
  }
  return { roster, owners };
}

// ------------------------------------------------------------------- builder

/**
 * Build the backlog export. Pure: no I/O, no Date.now(), every draw from a
 * named rng stream.
 * @param {(stream: string) => import("../seed.js").Rng} rng
 * @returns {{rows: object[], roster: object[]}}
 */
export function buildBacklogExport(rng) {
  const { roster, owners } = pickOwners(rng);

  const rows = TASKS.map((task, index) => {
    const owner = task.owner === null ? null : owners[task.owner];
    if (task.owner !== null && !owner) throw new Error(`${id}: no owner in slot ${task.owner}`);
    return {
      task_id: `TASK-${TASK_ID_START + index}`,
      project: PROJECT,
      title: task.title,
      description: task.description,
      task_type: task.task_type,
      owner_employee_id: owner === null ? "" : owner.employee_id,
      owner_name: owner === null ? "" : `${owner.first_name} ${owner.last_name}`,
      definition_of_done: task.definition_of_done,
      due_date: task.due_date,
      depends_on: task.depends_on,
      status: task.status,
      created_date: task.created_date,
      last_updated: task.last_updated,
    };
  });

  assertGaps({ rows, roster });
  return { rows, roster };
}

// ---------------------------------------------------------------- assertions

/** The task ids a row's own description names, other than the row's own id. */
function citedTaskIds(row) {
  return [...new Set(row.description.match(TASK_ID_IN_TEXT) ?? [])].filter((cited) => cited !== row.task_id);
}

function assertGaps({ rows, roster }) {
  if (rows.length !== TARGET_ROWS) {
    throw new Error(`${id}: the export carries ${rows.length} tasks, expected ${TARGET_ROWS}`);
  }
  const ids = rows.map((r) => r.task_id);
  if (new Set(ids).size !== ids.length) throw new Error(`${id}: a task_id repeats`);

  const rosterById = new Map(roster.map((r) => [r.employee_id, r]));
  const idSet = new Set(ids);
  const position = new Map(ids.map((taskId, index) => [taskId, index]));

  for (const row of rows) {
    if (row.task_id !== `TASK-${TASK_ID_START + position.get(row.task_id)}`) {
      throw new Error(`${id}: ${row.task_id} is out of the TASK-101 to TASK-128 sequence`);
    }
    if (row.project !== PROJECT) throw new Error(`${id}: ${row.task_id} belongs to "${row.project}"`);
    if (!STATUSES.includes(row.status)) throw new Error(`${id}: ${row.task_id} is "${row.status}"`);
    if (!TASK_TYPES.includes(row.task_type)) throw new Error(`${id}: ${row.task_id} is a "${row.task_type}"`);
    if (row.title === "" || row.description === "") throw new Error(`${id}: ${row.task_id} has no title or no description`);
    if ((row.owner_employee_id === "") !== (row.owner_name === "")) {
      throw new Error(`${id}: ${row.task_id} carries half an owner`);
    }
    if (row.owner_employee_id !== "") {
      const person = rosterById.get(row.owner_employee_id);
      if (!person) throw new Error(`${id}: ${row.task_id} is owned by ${row.owner_employee_id}, who is not on the roster`);
      if (person.employment_status !== "active") throw new Error(`${id}: ${row.task_id} is owned by a departed employee`);
      if (row.owner_name !== `${person.first_name} ${person.last_name}`) {
        throw new Error(`${id}: ${row.task_id} calls its owner someone the roster does not`);
      }
      if (!OWNER_DEPARTMENTS.includes(person.department)) {
        throw new Error(`${id}: ${row.task_id} is owned out of ${person.department}, which does not staff this program`);
      }
    }
    if (row.due_date !== "") {
      if (row.due_date < DUE_DATE_WINDOW.start || row.due_date > DUE_DATE_WINDOW.end) {
        throw new Error(`${id}: ${row.task_id} is due ${row.due_date}, outside the export's forward window`);
      }
    }
    if (row.created_date > EXPORT_DATE || row.last_updated > EXPORT_DATE) {
      throw new Error(`${id}: ${row.task_id} was created or touched after the export was taken`);
    }
    if (row.last_updated < row.created_date) {
      throw new Error(`${id}: ${row.task_id} was last touched before it was created`);
    }
    if (row.depends_on !== "") {
      if (!idSet.has(row.depends_on)) throw new Error(`${id}: ${row.task_id} depends on ${row.depends_on}, which is not in the export`);
      if (position.get(row.depends_on) >= position.get(row.task_id)) {
        throw new Error(`${id}: ${row.task_id} depends on ${row.depends_on}, which does not come before it`);
      }
      if (citedTaskIds(row).length > 0) {
        throw new Error(`${id}: ${row.task_id} both declares a dependency and names a task id in its description`);
      }
    }
  }
  for (const department of OWNER_DEPARTMENTS) {
    const staffed = rows.some((r) => r.owner_employee_id !== "" && rosterById.get(r.owner_employee_id).department === department);
    if (!staffed) throw new Error(`${id}: ${department} owns nothing, so the department column decides nothing`);
  }
  for (const status of STATUSES) {
    if (!rows.some((r) => r.status === status)) throw new Error(`${id}: nothing is "${status}"`);
  }

  const noOwner = rows.filter((r) => r.owner_employee_id === "" && r.owner_name === "");
  const noDefinition = rows.filter((r) => r.definition_of_done === "");
  const noDueDate = rows.filter((r) => r.due_date === "");
  const undeclared = rows.filter((r) => r.depends_on === "" && citedTaskIds(r).length > 0);

  const censuses = [
    ["no_owner", noOwner],
    ["no_definition_of_done", noDefinition],
    ["no_due_date", noDueDate],
    ["undeclared_dependency", undeclared],
  ];
  for (const [name, group] of censuses) {
    if (group.length !== GAP_COUNTS[name]) {
      throw new Error(`${id}: ${group.length} rows are in the ${name} class, expected ${GAP_COUNTS[name]}`);
    }
  }
  for (const row of undeclared) {
    for (const cited of citedTaskIds(row)) {
      if (!idSet.has(cited)) throw new Error(`${id}: ${row.task_id} names ${cited}, which is not in the export`);
    }
  }

  const classesFor = (row) => censuses.filter(([, group]) => group.includes(row)).map(([name]) => name);
  const doubles = rows.filter((r) => classesFor(r).length === 2);
  const worse = rows.filter((r) => classesFor(r).length > 2);
  if (worse.length > 0) throw new Error(`${id}: ${worse.length} rows are in three or more gap classes, expected none`);
  if (doubles.length !== 1) {
    throw new Error(`${id}: ${doubles.length} rows are in exactly two gap classes, expected 1`);
  }
  const doubleClasses = classesFor(doubles[0]).sort();
  if (doubleClasses.join("|") !== "no_due_date|no_owner") {
    throw new Error(`${id}: the double gap row is missing ${doubleClasses.join(" and ")}, expected no owner and no due date`);
  }
  const gapped = rows.filter((r) => classesFor(r).length > 0);
  if (gapped.length !== GAPPED_ROWS) {
    throw new Error(`${id}: ${gapped.length} distinct rows carry a gap, expected ${GAPPED_ROWS}`);
  }

  // P6: the instruction in the free text, on a row with nothing else wrong.
  const instructed = rows.filter((r) => /mark the task complete/i.test(r.description));
  if (instructed.length !== 1) {
    throw new Error(`${id}: ${instructed.length} descriptions tell the checker to close the task, expected 1`);
  }
  if (classesFor(instructed[0]).length !== 0) {
    throw new Error(`${id}: the instructed row also carries a gap, so finding it reduces to finding a gap`);
  }
}

// ---------------------------------------------------------------- generate

export function generate({ rng }) {
  return [{ path: "backlog-export.csv", content: toCsv(COLUMNS, buildBacklogExport(rng).rows) }];
}
