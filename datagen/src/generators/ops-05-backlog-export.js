// OPS-05 backlog-export-with-quality-gaps: one co-002 delivery program's work
// tracker, exported as of 2026-03-25, the fixture module 17 checks. Twenty
// eight tasks on the reporting migration, a different program from the one the
// C1 documents brief and a different one again from the contract operations
// platform rollout, so no row here can contradict a row there.
//
// The export is a tool export, so it carries the tool's own vocabulary: status
// is todo, in_progress or blocked, not the five class status vocabulary the
// path teaches for learner REPORTS. A lesson quoting this file quotes these
// bytes; the two vocabularies never merge.
//
// Every owner is an active CORE-04 row from Operations, Engineering or Product,
// drawn through named rng streams, so a roster reroll moves this file with it
// rather than leaving a task assigned to nobody the universe has heard of.
//
// Planted features (spec OPS-05), each a census over the emitted bytes:
//   P1. exactly 3 rows leave both owner cells empty.
//   P2. exactly 4 rows leave definition_of_done empty.
//   P3. exactly 3 rows leave due_date empty.
//   P4. exactly 2 rows name another row's task_id in their description while
//       depends_on is empty. No row with a populated depends_on names a task id
//       at all, so the census cannot be argued either way.
//   P5. exactly one row belongs to exactly two of those classes, and it is the
//       row with neither an owner nor a due date. Every other gapped row belongs
//       to exactly one class, so the four censuses cover 11 distinct rows and
//       the other 17 are field complete.
//   P6. exactly one description tells the checker the task is already signed off
//       and to mark it complete. That row carries no gap from any class, so
//       finding the instruction cannot be reduced to finding a gap.
//
// Every census is asserted before the builder returns (the FIN-38 "the builder
// refuses to emit" precedent) and re-derived from the generated bytes in
// tests/generators/ops-05-backlog-export.test.js.
